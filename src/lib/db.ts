import { createClient } from '@libsql/client';
import path from 'path';
import fs from 'fs';

// Database file path in project directory
const dbPath = path.join(process.cwd(), 'data');
if (!fs.existsSync(dbPath)) {
  fs.mkdirSync(dbPath, { recursive: true });
}

const dbFile = path.join(dbPath, 'meric.db');

export const db = createClient({
  url: `file:${dbFile}`,
});

let isInitialized = false;

export async function ensureDbInitialized() {
  if (isInitialized) return;

  // 1. Create tables
  await db.execute(`
    CREATE TABLE IF NOT EXISTS branches (
      id TEXT PRIMARY KEY,
      name TEXT NOT NULL,
      type TEXT NOT NULL,
      city TEXT NOT NULL,
      address TEXT NOT NULL,
      phone TEXT NOT NULL,
      email TEXT NOT NULL,
      map_url TEXT NOT NULL,
      features TEXT NOT NULL,
      order_num INTEGER NOT NULL DEFAULT 0
    );
  `);

  await db.execute(`
    CREATE TABLE IF NOT EXISTS staff (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      branch_id TEXT NOT NULL,
      name TEXT NOT NULL,
      title TEXT NOT NULL,
      hierarchy_level INTEGER NOT NULL DEFAULT 3,
      parent_id INTEGER,
      subject TEXT NOT NULL,
      photo TEXT NOT NULL,
      bio TEXT NOT NULL,
      education TEXT NOT NULL,
      experience_years INTEGER NOT NULL DEFAULT 5,
      order_num INTEGER NOT NULL DEFAULT 0,
      FOREIGN KEY (branch_id) REFERENCES branches(id)
    );
  `);

  await db.execute(`
    CREATE TABLE IF NOT EXISTS news_announcements (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      title TEXT NOT NULL,
      slug TEXT NOT NULL,
      type TEXT NOT NULL,
      branch_id TEXT NOT NULL DEFAULT 'all',
      image TEXT NOT NULL,
      summary TEXT NOT NULL,
      content TEXT NOT NULL,
      date TEXT NOT NULL,
      is_featured INTEGER NOT NULL DEFAULT 0,
      is_published INTEGER NOT NULL DEFAULT 1
    );
  `);

  await db.execute(`
    CREATE TABLE IF NOT EXISTS applications (
      id INTEGER PRIMARY KEY AUTOINCREMENT,
      parent_name TEXT NOT NULL,
      phone TEXT NOT NULL,
      email TEXT NOT NULL,
      student_name TEXT NOT NULL,
      grade_level TEXT NOT NULL,
      branch_id TEXT NOT NULL,
      notes TEXT,
      status TEXT NOT NULL DEFAULT 'bekliyor',
      created_at TEXT NOT NULL
    );
  `);

  await db.execute(`
    CREATE TABLE IF NOT EXISTS settings (
      key TEXT PRIMARY KEY,
      value TEXT NOT NULL
    );
  `);

  // Check if branches exist
  const existingBranches = await db.execute('SELECT COUNT(*) as count FROM branches');
  const count = Number(existingBranches.rows[0].count);

  if (count === 0) {
    await seedDatabase();
  }

  isInitialized = true;
}

